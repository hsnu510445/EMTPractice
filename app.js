/* 分岔情境：選項可帶 next（步驟id），或整個 action 步驟可帶 step.next，
   指定下一步要跳去哪個id；沒有指定就照陣列順序往下一步走。 */
function resolveNextIndex(){
  const sc = state.scenario;
  const step = sc.steps[state.stepIndex];
  const nextId = (step.type==="choice") ? state.lastChoiceNext : step.next;
  if(nextId){
    const idx = sc.steps.findIndex(s=>s.id===nextId);
    if(idx>=0) return idx;
  }
  return (state.stepIndex < sc.steps.length-1) ? state.stepIndex+1 : -1;
}

function addNextButton(){
  const nextRow = document.getElementById("nextRow");
  nextRow.innerHTML = "";
  const nextBtn = document.createElement("button");
  nextBtn.className = "btn btn-primary";
  nextBtn.textContent = (resolveNextIndex() >= 0) ? "繼續 →" : "查看結果";
  nextBtn.onclick = advance;
  nextRow.appendChild(nextBtn);
}

function advance(){
  document.onkeydown = null;
  const idx = resolveNextIndex();
  if(idx >= 0){
    state.stepIndex = idx;
    renderStep();
  } else {
    finishScenario();
  }
}

