function evaluateAction(toolId, target, meta){
  const sc = state.scenario;
  const step = sc.steps[state.stepIndex];
  let isCorrect;
  let deviceFlowNote = "";
  if(toolId === "nasalAirway" && step.correct && step.correct.nasalAirwayForbidden){
    isCorrect = false;
    deviceFlowNote = "顱底骨折時禁用鼻咽氣道（NPA），因為鼻腔插入可能加重顱腦損傷；改用口咽氣道（OPA）或其他更安全的氣道管理。";
  } else if(toolId==="oxygenMask" && step.correct.tool==="oxygenMask" && step.correct.oxygenSpec){
    const spec = step.correct.oxygenSpec;
    const deviceOk = meta && meta.device === spec.device;
    const flowOk = meta && meta.flow >= spec.flowMin && meta.flow <= spec.flowMax;
    isCorrect = deviceOk && flowOk && target===step.correct.target;
    if(!isCorrect){
      deviceFlowNote = "裝置或流量不太對，再確認一次適合這個情況的給氧裝置與流量範圍。";
    }
  } else if(toolId==="positionPatient" && step.correct.tool==="positionPatient" && step.correct.positionSpec){
    isCorrect = meta && meta.position === step.correct.positionSpec.position && target===step.correct.target;
    if(!isCorrect){
      deviceFlowNote = "這個姿勢不太適合目前的狀況，再想想看。";
    }
  } else if(toolId==="lookListenFeel" && step.correct.tool==="lookListenFeel" && typeof step.correct.respRate==="number"){
    isCorrect = meta && typeof meta.guess==="number" && Math.abs(meta.guess - step.correct.respRate) <= 2 && target===step.correct.target;
    if(!isCorrect){
      deviceFlowNote = "數字不太對，再仔細數一次（可以用碼表配合胸廓起伏，數30秒乘以2會比較準）。";
    }
  } else if(toolId==="gcsCheck" && step.correct.tool==="gcsCheck" && step.correct.gcsSpec){
    const spec = step.correct.gcsSpec;
    isCorrect = meta && meta.e===spec.e && meta.v===spec.v && meta.m===spec.m && target===step.correct.target;
    if(!isCorrect){
      deviceFlowNote = "三項分數中至少有一項不對，對照一下情境描述的睜眼／語言／肢體反應，再評一次。";
    }
  } else {
    const targetOk = target===step.correct.target || (step.correct.altTargets && step.correct.altTargets.includes(target));
    isCorrect = (toolId===step.correct.tool && targetOk);
  }

  if(isCorrect){
    state.answered = true;
    if(state.attempts===0) state.correctCount++;
    state.appliedLog.push({tool:toolId, target});
    renderBadges();
    renderAppliedLog();
    disableTray();
    if(toolId==="lookListenFeel" && breathState){ closeBreathCounter(); }

    addNote("action", `✅ ${toolLabel(toolId)} → ${targetLabel(target)}`);
    if(step.correct.reading){
      /* 任何帶有數據的步驟，解讀一律留到情境結束才揭曉，避免中途爆雷 */
      state.readingsLog.push({
        toolLabel: toolLabel(toolId), targetLabel: targetLabel(target),
        reading: step.correct.reading, explain: step.correct.explain
      });
      addNote("reading", `📟 ${toolLabel(toolId)}：${step.correct.reading}`);
      const simNote = meta && meta.simSummary ? (`<br><br>${meta.simSummary}`) : "";
      showReadingAndNext(step.correct.reading + simNote);
    } else {
      const extra = meta && meta.simSummary ? ("\n\n" + meta.simSummary) : "";
      showFeedbackAndNext(true, step.correct.explain + extra);
    }
    return;
  }

  state.attempts++;
  if(state.attempts===1){
    const mistake = (step.mistakes||[]).find(m=>m.tool===toolId && m.target===target);
    state.mistakes.push({
      question: step.prompt,
      yourAnswer: `${toolLabel(toolId)} → ${targetLabel(target)}`,
      correctAnswer: `${toolLabel(step.correct.tool)} → ${targetLabel(step.correct.target)}`,
      explain: step.correct.explain
    });
  }
  const specific = (step.mistakes||[]).find(m=>m.tool===toolId && m.target===target);
  const msg = specific ? specific.explain :
    (deviceFlowNote || `這不是目前最需要的處理。正確做法：${toolLabel(step.correct.tool)} → ${targetLabel(step.correct.target)}。${step.correct.explain}`);
  showFeedbackOnly(false, msg);

  state.selectedTool = null;
  updateDiagramHighlights();
  renderTrayTools();
  renderTechTools();
  document.getElementById("selectedToolHint").classList.add("hidden");
  if(state.attempts>=2) document.getElementById("hintBtn").classList.remove("hidden");
}

