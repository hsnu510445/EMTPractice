function onToolClick(tool){
  if(state.answered) return;
  if(tool.id==="positionPatient"){
    state.posOpen = !state.posOpen;
    document.getElementById("posWrap").classList.toggle("open", state.posOpen);
    return;
  }
  if(tool.id==="gcsCheck"){
    state.gcsSelected = {e:null, v:null, m:null};
    state.gcsHintOn = false;
    renderGcsPanel();
    document.getElementById("gcsModal").classList.add("open");
    return;
  }
  if(tool.id==="history"){
    openSampleModal();
    return;
  }
  if(tool.id==="handoverReport"){
    openHandoverModal();
    return;
  }
  if(tool.id==="generalImpression"){
    state.giViewed = new Set();
    state.giLog = [];
    state.giCurrentRegion = null;
    document.getElementById("giLog").innerHTML = "";
    document.getElementById("giItemsView").classList.add("hidden");
    document.getElementById("giDiagramView").classList.remove("hidden");
    renderGiDiagram();
    document.getElementById("giModal").classList.add("open");
    return;
  }
  if(tool.id==="ongoingMonitor"){
    state.monitorOpen = !state.monitorOpen;
    document.getElementById("monitorWrap").classList.toggle("open", state.monitorOpen);
    return;
  }
  if(tool.id==="cpr"){
    const step = state.scenario.steps[state.stepIndex];
    if(step.cprSim){ startCprSim(); return; }
  }
  if(tool.id==="spineBoard"){
    const step = state.scenario.steps[state.stepIndex];
    if(step.transportSim){ startTransportSim(); return; }
  }
  if(state.selectedTool===tool.id){ state.selectedTool = null; updateDiagramHighlights(); renderTrayTools(); renderTechTools(); document.getElementById("selectedToolHint").classList.add("hidden"); return; }
  state.selectedTool = tool.id;
  renderTrayTools();
  renderTechTools();
  if(!tool.needsTarget){
    evaluateAction(tool.id, tool.fixedTarget);
  } else {
    const hint = document.getElementById("selectedToolHint");
    hint.textContent = `已選擇「${tool.label}」，請點選病患身上要處理的部位`;
    hint.classList.remove("hidden");
    updateDiagramHighlights();
  }
}

