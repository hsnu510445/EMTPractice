function renderTriagePatientCard(card, p){
  const done = triageState.done[p.id];
  const allDone = p.checks.every(c=> done[c.id]);
  let checksHtml = "";
  p.checks.forEach(c=>{
    if(done[c.id]){
      checksHtml += `<div class="triage-check-found"><b>${TRIAGE_CHECK_LABELS[c.id]}：</b>${c.text}</div>`;
    }else{
      checksHtml += `<button class="triage-check-btn" data-check="${c.id}">▶ ${TRIAGE_CHECK_LABELS[c.id]}</button>`;
    }
  });
  card.innerHTML = `
    <h4>${p.label}</h4>
    <div class="triage-desc">${p.desc}</div>
    <div class="triage-checks">${checksHtml}</div>
    ${!allDone ? `<div class="triage-lock-hint">完成上面的評估後才能標記分類</div>` : ""}
    <div class="triage-tags ${allDone ? "" : "locked"}" id="tags-${p.id}"></div>`;
  card.querySelectorAll(".triage-check-btn").forEach(btn=>{
    btn.onclick = ()=>{
      done[btn.dataset.check] = true;
      renderTriagePatientCard(card, p);
    };
  });
  const tagsWrap = card.querySelector(`#tags-${p.id}`);
  TRIAGE_TAGS.forEach(tag=>{
    const btn = document.createElement("button");
    btn.className = "triage-tag-btn " + tag.cls + (triageState.tags[p.id]===tag.id ? " selected" : "");
    btn.textContent = tag.label;
    btn.disabled = !allDone;
    btn.onclick = ()=>{
      if(!allDone) return;
      triageState.tags[p.id] = tag.id;
      tagsWrap.querySelectorAll(".triage-tag-btn").forEach(b=> b.classList.remove("selected"));
      btn.classList.add("selected");
    };
    tagsWrap.appendChild(btn);
  });
}
function finishTriage(){
  const sc = triageState.scenario;
  stopTriageTimer();
  document.getElementById("triagePlayScreen").classList.add("hidden");
  document.getElementById("triageResultScreen").classList.remove("hidden");
  let correctCount = 0;
  const list = document.getElementById("triageResultList");
  list.innerHTML = "";
  sc.patients.forEach(p=>{
    const yourTag = triageState.tags[p.id];
    const isCorrect = yourTag === p.correctTag;
    if(isCorrect) correctCount++;
    const yourTagMeta = TRIAGE_TAGS.find(t=>t.id===yourTag);
    const correctTagMeta = TRIAGE_TAGS.find(t=>t.id===p.correctTag);
    const div = document.createElement("div");
    div.className = "triage-result-item " + (isCorrect ? "correct" : "wrong");
    div.innerHTML = `
      <div style="flex:1;">
        <div style="font-weight:700;">${p.label} ${isCorrect ? "✔" : "✘"}</div>
        <div style="color:var(--muted);margin:2px 0;">${p.desc}</div>
        <div>你的分類：<span class="triage-badge ${yourTagMeta.cls}">${yourTagMeta.label}</span>
        ${!isCorrect ? ` → 正確：<span class="triage-badge ${correctTagMeta.cls}">${correctTagMeta.label}</span>` : ""}</div>
        <div style="margin-top:4px;color:var(--muted);">${p.explain}</div>
      </div>`;
    list.appendChild(div);
  });
  const totalMilliseconds = Object.values(triageState.patientTimes).reduce((sum, time) => sum + time, 0);
  document.getElementById("triageScore").textContent = `${correctCount} / ${sc.patients.length} 位分類正確 · 總時間 ${formatTriageTime(totalMilliseconds)}`;
  document.getElementById("triageResultList").insertAdjacentHTML("afterbegin", `<div class="triage-time-summary">每位傷患：${sc.patients.map(p => `${p.label} ${formatTriageTime(triageState.patientTimes[p.id] || 0)}`).join("　・　")}</div>`);
  const triageRealCaseBox = document.getElementById("triageRealCaseBox");
  triageRealCaseBox.classList.add("hidden");
  triageRealCaseBox.innerHTML = "";
  if(sc.realCase){
    triageRealCaseBox.innerHTML = `
      <h3>延伸閱讀：真實重大事件</h3>
      <p><b>${sc.realCase.title}</b></p>
      <p>${sc.realCase.summary}</p>
      <p><b>和本題的連結：</b>${sc.realCase.learningPoint}</p>
      <p><a href="${sc.realCase.source}" target="_blank" rel="noopener noreferrer">查看來源網站</a></p>`;
    triageRealCaseBox.classList.remove("hidden");
  }
}
document.getElementById("triageSubmitBtn").onclick = ()=>{
  if(!triageState) return;
  const sc = triageState.scenario;
  const patient = sc.patients[triageState.currentPatientIndex];
  const done = triageState.done[patient.id];
  if(!patient.checks.every(check=>done[check.id])){
    alert("請先完成這位傷患的所有評估，再進行下一步。");
    return;
  }
  if(!triageState.tags[patient.id]){
    alert("請先選擇這位傷患的檢傷分類。");
    return;
  }
  triageState.patientTimes[patient.id] = Math.round(performance.now() - triageState.patientStartedAt);
  if(triageState.currentPatientIndex === sc.patients.length - 1){
    finishTriage();
    return;
  }
  triageState.currentPatientIndex++;
  triageState.patientStartedAt = performance.now();
  renderTriagePatientGrid();
  updateTriageTimer();
};
