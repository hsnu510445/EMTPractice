let commandState = null;

function renderCommandList(){
  const grid = document.getElementById("commandGrid");
  grid.innerHTML = "";
  COMMAND_SCENARIOS.forEach(sc=>{
    const card = document.createElement("div");
    card.className = "card";
    card.innerHTML = `<span class="tag">分配隊友・${sc.crew.length}人小隊</span><h3>${sc.title}</h3><p class="summary">${sc.intro}</p>`;
    card.onclick = ()=> startCommand(sc.id);
    grid.appendChild(card);
  });
}
function startCommand(id){
  const sc = COMMAND_SCENARIOS.find(s=>s.id===id);
  commandState = { scenario: sc, assign: {}, eventsStarted:false, eventIdx:0, eventScore:0, stability:100, trust:100, eventLog:[] };
  document.getElementById("commandListScreen").classList.add("hidden");
  document.getElementById("commandPlayScreen").classList.remove("hidden");
  document.getElementById("commandIntro").textContent = sc.intro;
  document.getElementById("commandLivePanel").classList.add("hidden");
  document.getElementById("commandSubmitBtn").textContent = "送出分工";
  const crewBox = document.getElementById("commandCrewBox");
  crewBox.innerHTML = sc.crew.map(c=>`<div class="command-crew-item">👤 ${c.label}</div>`).join("");
  const list = document.getElementById("commandTaskList");
  list.innerHTML = "";
  sc.tasks.forEach(t=>{
    const card = document.createElement("div");
    card.className = "command-task-card";
    const options = `<option value="">－請指派隊友－</option>` + sc.crew.map(c=>`<option value="${c.id}">${c.label}</option>`).join("");
    card.innerHTML = `<h4>${t.label}</h4><select data-task="${t.id}">${options}</select>`;
    card.querySelector("select").onchange = (e)=>{ commandState.assign[t.id] = e.target.value; };
    list.appendChild(card);
  });
}
document.getElementById("commandSubmitBtn").onclick = ()=>{
  if(commandState.eventsStarted && commandState.eventIdx < commandState.scenario.events.length){
    renderCommandEvent();
    return;
  }
  const sc = commandState.scenario;
  const unassigned = sc.tasks.filter(t=> !commandState.assign[t.id]);
  if(unassigned.length>0){
    alert(`還有 ${unassigned.length} 項任務還沒有指派隊友，請全部指派後再送出。`);
    return;
  }
  const usedCrew = Object.values(commandState.assign);
  const dup = usedCrew.some((id,i)=> usedCrew.indexOf(id)!==i);
  if(dup){
    alert("每位隊友只能負責一項任務，請確認沒有把同一個人分配到兩項任務、也沒有人閒著沒事做。");
    return;
  }
  startCommandEvents();
};
function startCommandEvents(){
  commandState.eventsStarted = true;
  document.getElementById("commandTaskList").classList.add("hidden");
  document.getElementById("commandLivePanel").classList.remove("hidden");
  document.getElementById("commandSubmitBtn").textContent = "接聽下一則無線電";
  renderCommandEvent();
}
function renderCommandEvent(){
  const state = commandState;
  const events = state.scenario.events;
  if(state.eventIdx >= events.length){
    finishCommand();
    return;
  }
  const event = events[state.eventIdx];
  document.getElementById("commandRoundLabel").textContent = `臨場事件 ${state.eventIdx + 1} / ${events.length}`;
  document.getElementById("commandStability").textContent = state.stability;
  document.getElementById("commandTrust").textContent = state.trust;
  document.getElementById("commandRadio").lastChild && (document.getElementById("commandRadio").lastChild.textContent = event.prompt);
  const radio = document.getElementById("commandRadio");
  radio.textContent = event.prompt;
  const list = document.getElementById("commandChoiceList");
  list.innerHTML = state.scenario.crew.map(c=>`<button class="command-choice-btn" data-crew="${c.id}">派 ${c.label} 處理</button>`).join("");
  list.querySelectorAll("button").forEach(btn=>btn.onclick = ()=> resolveCommandEvent(btn.dataset.crew));
}
function resolveCommandEvent(crewId){
  const state = commandState;
  const event = state.scenario.events[state.eventIdx];
  const crew = state.scenario.crew.find(c=>c.id===crewId);
  const correct = crewId === event.correctCrew;
  if(correct){
    state.eventScore++;
    state.trust = Math.min(100, state.trust + 3);
    state.eventLog.push(`✓ ${crew.label} 正確接手：${event.explain}`);
  }else{
    state.stability = Math.max(0, state.stability - event.impact);
    state.trust = Math.max(0, state.trust - 10);
    state.eventLog.push(`✕ ${crew.label} 被派去處理，現場延誤。建議：${event.explain}`);
  }
  document.getElementById("commandEventLog").innerHTML = state.eventLog.map(entry=>`<div class="command-log-entry">${entry}</div>`).join("");
  state.eventIdx++;
  document.getElementById("commandChoiceList").querySelectorAll("button").forEach(btn=>btn.disabled=true);
  document.getElementById("commandSubmitBtn").textContent = state.eventIdx < state.scenario.events.length ? "接聽下一則無線電" : "查看任務報告";
  document.getElementById("commandStability").textContent = state.stability;
  document.getElementById("commandTrust").textContent = state.trust;
}
function finishCommand(){
  const sc = commandState.scenario;
  document.getElementById("commandPlayScreen").classList.add("hidden");
  document.getElementById("commandResultScreen").classList.remove("hidden");
  let correctCount = 0;
  const list = document.getElementById("commandResultList");
  list.innerHTML = "";
  sc.tasks.forEach(t=>{
    const yourCrewId = commandState.assign[t.id];
    const isCorrect = yourCrewId === t.correctCrew;
    if(isCorrect) correctCount++;
    const yourCrew = sc.crew.find(c=>c.id===yourCrewId);
    const correctCrew = sc.crew.find(c=>c.id===t.correctCrew);
    const div = document.createElement("div");
    div.className = "command-result-item " + (isCorrect ? "correct" : "wrong");
    div.innerHTML = `
      <div style="flex:1;">
        <div style="font-weight:700;">${t.label} ${isCorrect ? "✔" : "✘"}</div>
        <div>你的指派：${yourCrew.label}${!isCorrect ? ` → 建議：${correctCrew.label}` : ""}</div>
        <div style="margin-top:4px;color:var(--muted);">${t.explain}</div>
      </div>`;
    list.appendChild(div);
  });
  document.getElementById("commandScore").textContent = `${correctCount + commandState.eventScore} / ${sc.tasks.length + sc.events.length} 次判斷正確・穩定度 ${commandState.stability}%`;
  const eventSummary = document.createElement("div");
  eventSummary.className = "command-result-item";
  eventSummary.innerHTML = `<div><b>臨場調度報告</b><div>團隊信任：${commandState.trust}%</div><div style="margin-top:4px;color:var(--muted);">${commandState.eventLog.join(" ")}</div></div>`;
  list.appendChild(eventSummary);
}
