function startTriage(id){
  const sc = TRIAGE_SCENARIOS.find(s=>s.id===id);
  if(triageState?.timerId) clearInterval(triageState.timerId);
  const startedAt = performance.now();
  triageState = { scenario: sc, currentPatientIndex: 0, tags: {}, done: {}, patientTimes: {}, totalStartedAt: startedAt, patientStartedAt: startedAt, timerId: null };
  sc.patients.forEach(p=> triageState.done[p.id] = {});
  document.getElementById("triageListScreen").classList.add("hidden");
  document.getElementById("triagePlayScreen").classList.remove("hidden");
  document.getElementById("triageIntro").textContent = sc.intro;
  startTriageTimer();
  renderTriagePatientGrid();
}
function formatTriageTime(milliseconds){
  const seconds = Math.floor(milliseconds / 1000);
  return `${String(Math.floor(seconds / 60)).padStart(2,"0")}:${String(seconds % 60).padStart(2,"0")}`;
}
function updateTriageTimer(){
  if(!triageState) return;
  const now = performance.now();
  document.getElementById("triagePatientTimer").textContent = formatTriageTime(now - triageState.patientStartedAt);
  document.getElementById("triageTotalTimer").textContent = formatTriageTime(now - triageState.totalStartedAt);
}
function startTriageTimer(){
  if(triageState.timerId) clearInterval(triageState.timerId);
  triageState.timerId = setInterval(updateTriageTimer, 250);
  updateTriageTimer();
}
function stopTriageTimer(){
  if(triageState?.timerId) clearInterval(triageState.timerId);
  if(triageState) triageState.timerId = null;
}
