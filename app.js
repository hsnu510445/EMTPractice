function cprAfterVentilate(){
  const aedDue = (cprState.padsPlaced.a && cprState.padsPlaced.c) ? (cprState.cycle % 2 === 0 || cprState.cycle===1) : cprState.cycle===1;
  if(!(cprState.padsPlaced.a && cprState.padsPlaced.c) && cprState.cycle===1){
    cprState.phase = "pads";
    cprState.padsReturnPhase = "clear";
    renderCprPhase();
    return;
  }
  if(aedDue){
    cprState.phase = "clear";
    renderCprPhase();
  } else {
    cprCheckResolutionOrNextCycle();
  }
}

function cprAfterAed(){
  cprCheckResolutionOrNextCycle();
}

function cprCheckResolutionOrNextCycle(){
  const resolveChance = cprState.cycle>=4 ? 1 : cprState.cycle===3 ? 0.7 : cprState.cycle===2 ? 0.35 : 0;
  if(!cprState.resolved && Math.random() < resolveChance){
    cprState.resolved = true;
    const outcomes = ["病患開始有自主呼吸與脈搏（ROSC）！", "進階救護人員抵達，準備接手後續處置。", "已抵達醫院，準備交班。"];
    const outcome = outcomes[Math.floor(Math.random()*outcomes.length)];
    addCprLog("🎉 " + outcome);
    finishCprSim(outcome);
    return;
  }
  cprState.cycle++;
  cprState.phase = "compress";
  renderCprPhase();
}

function finishCprSim(outcomeText){
  if(cprState.beatTimer) clearInterval(cprState.beatTimer);
  if(cprState.tickerTimer) clearInterval(cprState.tickerTimer);
  document.getElementById("cprModal").classList.remove("open");

  const acc = cprState.accuracyCounts;
  const totalClicks = acc.good + acc.ok + acc.off;
  const accuracyPct = totalClicks>0 ? Math.round((acc.good/totalClicks)*100) : null;

  let summary = `CPR模擬結束：共進行 ${cprState.cycle} 輪，${outcomeText}`;
  if(accuracyPct!==null) summary += ` 你按壓的節奏準確率約 ${accuracyPct}%（良好${acc.good}／尚可${acc.ok}／不佳${acc.off}）。`;
  summary += cprState.handoffRequested ? " 你有主動請求換手，很好的團隊意識。" : (cprState.role==="primary" ? " 這次全程自己按壓，記得體力不夠時要主動喊換手。" : "");
  addNote("action", "✅ 完成CPR模擬：" + outcomeText);

  const step = state.scenario.steps[state.stepIndex];
  state.answered = true;
  if(state.attempts===0) state.correctCount++;
  state.appliedLog.push({tool:"cpr", target:"chest"});
  renderBadges();
  renderAppliedLog();
  disableTray();
  showFeedbackAndNext(true, (step.correct.explain||"") + "\n\n" + summary);
}

