function setupBvmDrag(){
  const handle = document.getElementById("bvmHandle");
  const trackHeight = 120;
  const squeezeThreshold = trackHeight*0.5;
  let dragging=false, startY=0, downTime=0, reachedSqueeze=false;

  const onDown = (e)=>{
    if(!cprState || cprState.bvmBreaths>=2) return;
    dragging = true; startY = e.clientY; downTime = performance.now(); reachedSqueeze = false;
    handle.style.transition = "none"; /* 拖曳中跟著滑鼠即時移動，放開時才用動畫彈回去 */
    handle.setPointerCapture && handle.setPointerCapture(e.pointerId);
  };
  const onMove = (e)=>{
    if(!dragging) return;
    let dy = e.clientY - startY;
    dy = Math.max(0, Math.min(trackHeight-28, dy));
    handle.style.transform = `translateX(-50%) translateY(${dy}px)`;
    if(dy >= squeezeThreshold && !reachedSqueeze){
      reachedSqueeze = true;
      handle.classList.add("squeezing");
    }
  };
  /* 放開滑鼠（不管有沒有先拖回上面）就算完成這一口氣的擠壓＋放開動作，比較符合直覺 */
  const finishGesture = ()=>{
    if(!dragging) return;
    dragging = false;
    const holdTime = performance.now() - downTime;
    handle.style.transition = "";
    handle.classList.remove("squeezing");
    handle.style.transform = "translateX(-50%) translateY(0px)";
    if(reachedSqueeze) registerBvmBreath(holdTime);
  };
  handle.onpointerdown = onDown;
  handle.onpointermove = onMove;
  handle.onpointerup = finishGesture;
  handle.onpointercancel = finishGesture;
}

function registerBvmBreath(holdTimeMs){
  const fb = document.getElementById("bvmFeedback");
  if(holdTimeMs < 250){
    fb.className = "cpr-hit-feedback off";
    fb.textContent = "太快了，給氣時間至少約1秒，讓胸廓看得到起伏。";
    return;
  }
  if(holdTimeMs > 2200){
    fb.className = "cpr-hit-feedback ok";
    fb.textContent = "稍微久了一點，注意不要過度通氣。";
  } else {
    fb.className = "cpr-hit-feedback good";
    fb.textContent = "✔ 給氣速度剛好";
  }
  cprState.bvmBreaths++;
  document.getElementById("bvmCount").textContent = `${cprState.bvmBreaths} / 2 口氣`;
  if(cprState.bvmBreaths >= 2){
    addCprLog("你用BVM給予了2次人工呼吸。");
    setTimeout(()=> cprAfterVentilate(), 500);
  }
}

function renderCprCompressPrimary(){
  const body = document.getElementById("cprBody");
  body.innerHTML = `
    <div class="cpr-instruction">跟著節奏點擊紅色圓圈按壓（胸骨下半部）</div>
    <div class="cpr-chest-target" id="cprChestTarget">壓</div>
    <div class="cpr-hit-feedback" id="cprHitFeedback"></div>
    <div class="cpr-count" id="cprCount">0 / 30</div>`;
  const interval = 550;
  cprState.cycleStartTime = performance.now();
  const target = document.getElementById("cprChestTarget");
  target.onclick = ()=>{
    const now = performance.now();
    const elapsed = now - cprState.cycleStartTime;
    const nearestBeat = Math.round(elapsed / interval) * interval;
    const delta = Math.abs(elapsed - nearestBeat);
    let tier = "off";
    if(delta < 130) tier = "good"; else if(delta < 260) tier = "ok";
    cprState.accuracyCounts[tier]++;
    const fb = document.getElementById("cprHitFeedback");
    fb.className = "cpr-hit-feedback " + tier;
    fb.textContent = tier==="good" ? "✔ 節奏很好" : tier==="ok" ? "還可以，稍微跟緊一點" : "節奏不對，太快或太慢";
    cprState.compressionsThisCycle++;
    document.getElementById("cprCount").textContent = `${cprState.compressionsThisCycle} / 30`;
    cprState.fatigue = Math.min(100, cprState.fatigue + 1.2);
    renderCprFatigue();
    if(cprState.compressionsThisCycle >= 30){
      cprEndCompressPhase();
    }
  };
  if(cprState.beatTimer) clearInterval(cprState.beatTimer);
  cprState.beatTimer = setInterval(()=>{
    target.classList.remove("beat");
    void target.offsetWidth;
    target.classList.add("beat");
  }, interval);
}

